def seed_all(db: Session) -> None:
    """Заполняет пустую базу стартовыми данными. На непустой базе ничего не трогает."""

    if db.query(Tier).count() == 0:
        for t in TIERS:
            db.add(Tier(**t))
        db.commit()

    if db.query(Scenario).count() == 0:
        for idx, s in enumerate(SCENARIOS):
            scenario = Scenario(
                id=idx + 1,
                code=s["code"],
                category=s["category"],
                description=s["description"],
                visual=s["visual"],
                options_heading="Ваши действия?",
                order_index=idx,
                is_active=True,
            )
            db.add(scenario)
            db.flush()  # чтобы scenario.id был доступен для options ниже

            for oidx, (code, label, points, explanation) in enumerate(s["options"]):
                db.add(
                    ScenarioOption(
                        code=code,
                        scenario_id=scenario.id,
                        label=label,
                        points=points,
                        explanation=explanation,
                        order_index=oidx,
                    )
                )
        db.commit()

    if db.query(AdminUser).count() == 0:
        db.add(
            AdminUser(
                username=settings.admin_default_username,
                password_hash=hash_password(settings.admin_default_password),
            )
        )
        db.commit()
